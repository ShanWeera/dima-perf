def cargo_about(binary, manifest, about):
    result = subprocess.run(
        [binary, "generate", "--format", "json", "-c", str(ROOT / "about.toml"), "-m", str(ROOT / manifest), "--locked", "--fail"],
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    return json.loads(result.stdout)


def render(reports):
    # Merge licences by (id, text) and crates by (name, version) across both binaries.
    licences = {}
    crates = {}
    for report in reports:
        for c in report["crates"]:
            pkg = c["package"]
            crates[(pkg["name"], pkg["version"])] = c.get("license") or pkg.get("license") or "?"
        for lic in report["licenses"]:
            # Some crates ship licence texts with CRLF line endings; the notices are LF-only.
            text = lic["text"].replace("\r\n", "\n").replace("\r", "\n").strip()
            key = (lic["id"], text)
            entry = licences.setdefault(key, {"id": lic["id"], "name": lic["name"], "text": text, "used_by": set()})
            for u in lic["used_by"]:
                entry["used_by"].add((u["crate"]["name"], u["crate"]["version"]))
    # Only distributed crates: drop the workspace's own packages.
    own = {"dima", "dima-core", "dima-gui"}
    for key in [k for k in crates if k[0] in own]:
        del crates[key]
    out = [HEADER.format(easel=EASEL)]
    out.append("| Crate | Version | Licence |\n|---|---|---|\n")
    for (name, version), lic in sorted(crates.items(), key=lambda kv: (kv[0][0].lower(), kv[0][1])):
        out.append(f"| {name} | {version} | {lic} |\n")
    out.append("\n### Licence texts\n")
    ordered = sorted(
        (e for e in licences.values() if any(c[0] not in own for c in e["used_by"])),
        key=lambda e: (e["id"], sorted(e["used_by"])[0]),
    )
    for e in ordered:
        users = ", ".join(f"{n} {v}" for n, v in sorted(e["used_by"]) if n not in own)
        out.append(f"\n#### {e['name']} ({e['id']})\n\nUsed by: {users}\n\n```text\n{e['text']}\n```\n")
    return "".join(out)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", action="store_true", help="fail if THIRD-PARTY-NOTICES.md is out of date")
    p.add_argument("--cargo-about", default="cargo-about", help="the cargo-about executable")
    args = p.parse_args()
    text = render([cargo_about(args.cargo_about, m, ROOT / "about.toml") for m in BINARIES])
    if args.check:
        if OUT.read_text() != text:
            print("THIRD-PARTY-NOTICES.md is out of date: run python3 scripts/notices/generate.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
