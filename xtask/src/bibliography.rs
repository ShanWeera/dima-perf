//! The bibliography page, the citation data and the BibTeX database of the documentation site,
//! and the method references listed in `CITATION.cff`, all from the citation registry.

use std::cmp::Ordering;

use dima_core::citations::{self, Citation, Tier};
use dima_core::config::{Alphabet, Estimator};
use serde_json::{Map, Value, json};
use unicode_normalization::UnicodeNormalization;
use unicode_normalization::char::is_combining_mark;

use crate::markdown::linkify;

/// The references behind the methods any run can use (every estimator, both alphabets,
/// alphabet detection, similarity-weighted entropy, conserved sequences), without the DiMA
/// paper itself (it is the preferred citation) and in a stable order.
pub fn method_references() -> Vec<&'static Citation> {
    let mut keys: Vec<String> = Vec::new();
    for estimator in [
        Estimator::Dima,
        Estimator::ChaoWangJost,
        Estimator::MillerMadow,
        Estimator::Raw,
    ] {
        for alphabet in [Alphabet::Protein, Alphabet::Dna] {
            let used = dima_core::provenance::MethodsUsed {
                estimator,
                alphabet,
                alphabet_detected: true,
                similarity_weighted_entropy: true,
            };
            for r in dima_core::provenance::references(used) {
                keys.push(r.key);
            }
        }
    }
    keys.extend(dima_core::hcs::REFERENCES.iter().map(|k| (*k).to_owned()));
    // Conserved regions of eligible positions only (`--hcs-eligible-only`) cite it too.
    keys.push(dima_core::hcs::ELIGIBLE_ONLY_REFERENCE.to_owned());
    let mut seen = std::collections::BTreeSet::new();
    keys.into_iter()
        .filter(|k| k != citations::DIMA_PAPER && seen.insert(k.clone()))
        .filter_map(|k| citations::by_key(&k))
        .collect()
}

/// The order of references within each section of the Bibliography page and in the reference
/// list of every documentation page: the word an entry starts with (a standard's designation,
/// otherwise the first author's family name; ignoring case and accents, numbers by value), year,
/// in-text
/// label (so `Grüning, Chilton et al. 2018` comes before `Grüning, Dale et al. 2018`, and 2024a
/// before 2024b), key.
fn author_year(a: &Citation, b: &Citation) -> Ordering {
    let first = |c: &Citation| {
        fold(
            c.designation()
                .unwrap_or_else(|| c.authors.first().map_or("", |x| x.0)),
        )
    };
    natural(&first(a), &first(b))
        .then(a.year.cmp(&b.year))
        .then_with(|| a.short().cmp(&b.short()))
        .then(a.key.cmp(b.key))
}

/// `s` in lower case without accents (canonical decomposition without combining marks), so that
/// `Böck` sorts with `Bock` and `Marçais` with `Marcais`.
fn fold(s: &str) -> String {
    s.nfd()
        .filter(|&c| !is_combining_mark(c))
        .collect::<String>()
        .to_lowercase()
}

/// Compares text byte by byte, except that runs of ASCII digits compare as numbers, so
/// `rfc 793` comes before `rfc 4180`.
fn natural(a: &str, b: &str) -> Ordering {
    fn digits(s: &[u8]) -> usize {
        s.iter().take_while(|c| c.is_ascii_digit()).count()
    }
    fn value(run: &[u8]) -> &[u8] {
        let zeros = run.iter().take_while(|&&c| c == b'0').count();
        &run[zeros..]
    }
    let (mut x, mut y) = (a.as_bytes(), b.as_bytes());
    loop {
        match (x.first(), y.first()) {
            (None, None) => return Ordering::Equal,
            (None, Some(_)) => return Ordering::Less,
            (Some(_), None) => return Ordering::Greater,
            (Some(p), Some(q)) if p.is_ascii_digit() && q.is_ascii_digit() => {
                let (nx, ny) = (digits(x), digits(y));
                let (vx, vy) = (value(&x[..nx]), value(&y[..ny]));
                let o = vx.len().cmp(&vy.len()).then_with(|| vx.cmp(vy));
                if o != Ordering::Equal {
                    return o;
                }
                x = &x[nx..];
                y = &y[ny..];
            }
            (Some(p), Some(q)) => {
                if p != q {
                    return p.cmp(q);
                }
                x = &x[1..];
                y = &y[1..];
            }
        }
    }
}

fn heading(tier: Tier) -> &'static str {
    match tier {
        Tier::Domain => {
            "Bioinformatics, computational biology, virology, microbiology, ecology and evolution, and biostatistics"
        }
        Tier::General => "General sources [general]",
        Tier::Standard => "Standards and specifications [standard]",
    }
}

/// The bibliography page: every reference, grouped by citation-policy tier.
pub fn page() -> String {
    let mut out = String::from(
        "---\ntitle: Bibliography\ndescription: Every reference cited by DiMA's help, documentation and desktop app.\n---\n\n<!-- Generated by `cargo xtask gen` from crates/dima-core/src/citations.rs; do not edit. -->\n\n",
    );
    out.push_str(
        "Every reference cited by `dima`, its help texts, the desktop app and these pages comes \
         from one registry in the source code. References are grouped by the project's citation \
         policy: peer-reviewed work in the field first; general computer-science, statistics or \
         human-computer-interaction sources only where they are the primary source of a method \
         or measurement no domain source provides (marked [general]); and standards and \
         specifications, cited for what they define, such as the symbols a sequence database \
         uses in its files (marked [standard]). See [Citing DiMA](/reference/citing/) for how to cite DiMA itself.\n\n",
    );
    for tier in [Tier::Domain, Tier::General, Tier::Standard] {
        let refs: Vec<&Citation> = citations::all()
            .iter()
            .copied()
            .filter(|c| c.tier == tier)
            .collect();
        if refs.is_empty() {
            continue;
        }
        out.push_str(&format!(
            "## {}\n\n",
            crate::markdown::escape(heading(tier))
        ));
        let mut refs = refs;
        refs.sort_by(|a, b| author_year(a, b));
        for c in refs {
            out.push_str(&format!("- {}\n", linkify(&c.listed_text())));
        }
        out.push('\n');
    }
    while out.ends_with("\n\n") {
        out.pop();
    }
    out
}

/// One BibTeX database: this software, then every reference by key.
pub fn bibtex() -> String {
    let mut out = String::from(
        "% Generated by `cargo xtask gen` from crates/dima-core/src/citations.rs; do not edit.\n\n",
    );
    out.push_str(citations::software_bibtex(citations::SOFTWARE_VERSION).trim_end());
    out.push_str("\n\n");
    for c in citations::all() {
        out.push_str(c.bibtex().trim_end());
        out.push_str("\n\n");
    }
    out.pop();
    out
}

/// The in-text label of a reference on the documentation site, as in the help texts and the
/// desktop app: `List et al. 2017`.
fn label(c: &Citation) -> String {
    c.short()
}

/// The citation data of the documentation site (`docs/src/references.json`), from which
/// `docs/plugins/rehype-registry-citations.mjs` renders every in-text citation and reference
/// list. For every key: its in-text `label`; its full `text` as `dima cite` prints it (with a
/// year letter where the label has one), without the DOI or URL it ends with; that `link`
/// (`label` as printed, resolvable `href`), or null; and its rank in [`author_year`] order
/// (`order`).
pub fn references_json() -> String {
    let mut sorted: Vec<&Citation> = citations::all().to_vec();
    sorted.sort_by(|a, b| author_year(a, b));
    let mut map = Map::new();
    // `all()` is sorted by key, so the file lists keys in order whether or not serde_json keeps
    // insertion order.
    for &c in citations::all() {
        let text = c.listed_text();
        let (body, link) = match (c.link(), c.href()) {
            (Some(shown), Some(href)) => {
                let body = text
                    .strip_suffix(&format!(" {shown}"))
                    .expect("Citation::text ends with Citation::link")
                    .to_owned();
                (body, json!({ "label": shown, "href": href }))
            }
            _ => (text, Value::Null),
        };
        let order = sorted
            .iter()
            .position(|s| s.key == c.key)
            .expect("every reference is in the sorted list");
        map.insert(
            c.key.to_owned(),
            json!({ "label": label(c), "text": body, "link": link, "order": order }),
        );
    }
    let mut s =
        serde_json::to_string_pretty(&Value::Object(map)).expect("JSON values always serialise");
    s.push('\n');
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn natural_order_compares_numbers_by_value() {
        assert_eq!(natural("rfc 793", "rfc 4180"), Ordering::Less);
        assert_eq!(natural("rfc 8259", "rfc 9309"), Ordering::Less);
        assert_eq!(natural("uax #15", "uax #44"), Ordering::Less);
        assert_eq!(natural("wcag 2.2", "wcag2ict"), Ordering::Less);
        assert_eq!(natural("a", "a"), Ordering::Equal);
        assert_eq!(natural("", "a"), Ordering::Less);
        assert_eq!(natural(&fold("Böck"), &fold("Bolyen")), Ordering::Less);
        assert_eq!(natural(&fold("Marçais"), &fold("Martin")), Ordering::Less);
    }

    #[test]
    fn site_citations_repeat_the_registry() {
        let data: Value = serde_json::from_str(&references_json()).unwrap();
        let data = data.as_object().unwrap();
        assert_eq!(data.len(), citations::all().len());
        let mut orders: Vec<u64> = Vec::new();
        for c in citations::all() {
            let e = &data[c.key];
            let mut text = e["text"].as_str().unwrap().to_owned();
            if let Some(link) = e["link"].as_object() {
                assert_eq!(link["href"].as_str(), c.href().as_deref());
                text = format!("{text} {}", link["label"].as_str().unwrap());
            }
            assert_eq!(text, c.listed_text(), "{}", c.key);
            assert_eq!(e["label"].as_str().unwrap(), c.short());
            orders.push(e["order"].as_u64().unwrap());
        }
        orders.sort_unstable();
        assert!(orders.iter().enumerate().all(|(i, &o)| o == i as u64));
    }
}
